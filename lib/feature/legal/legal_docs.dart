///   改这里之前先改那份真源,再原样同步过来 —— 不要在 App 侧润色法律文本。
///
/// ★ 小程序的隐私政策走微信官方隐私保护指引(pages/privacy),那是小程序独有
///   机制,App 上不存在,所以 App 必须自己承载 —— 见下面 privacy_policy 的注释。
@immutable
class LegalSection {
  const LegalSection(this.h, this.p);

  /// 小节标题(对应 JS 里的 `h`)。
  final String h;

  /// 小节正文(对应 JS 里的 `p`);`\n` 是原文里的换行,渲染时保留。
  final String p;
}

@immutable
class LegalDoc {
  const LegalDoc({
    required this.title,
    this.version,
    this.updatedAt,
    this.intro,
    this.sections = const <LegalSection>[],
  });

  final String title;

  /// 与真源一一对应保留。小程序的协议页同样不渲染版本号(只渲染生效日期),
  /// 这里跟随,不自作主张多显示一行。
  final String? version;

  final String? updatedAt;
  final String? intro;
  final List<LegalSection> sections;

  /// 正文缺席 = 「待提供」态。页面据此渲染占位而不是空白页。
  bool get pending => sections.isEmpty;
}

